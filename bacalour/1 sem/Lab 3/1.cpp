#include <iostream> //подключаем библиотеку iostream
#include <cmath>    //подключаем библиотеку cmath для нахождения ln и arctg
#include <clocale>  //подключаем библиотеку clocale
using namespace std; //используем пространство имён std

int main()//основная функция main
 { 
    setlocale(LC_ALL, ".UTF-8"); // Для нормального вывода русских букв
    cout << "Введите a и b через пробел: ";
    double a, b;
    cin >> a >> b; //вводим параметры a и b
    
    double k = (b - a) / 10; // k - это шаг в цикле
    double se = 0, sn = 0, curr; 
    int n = 3; // n = количество элементов для первой суммы

    for (double x = a; x <= b + k/2; x += k)
    { 
        cout << "X = " << x << "    "; //вывод текущего x
        
        // 1. Считаем первую сумму (sn для заданного n=3) 
        sn = 0; // обнуляем сумму для каждого нового x
        curr = x; // первый член ряда (при j=0): x^(4*0+1)/(4*0+1) = x
        for (int j = 0; j <= n; j++) 
        {
            sn += curr;
            // Рекуррентная формула: a{j+1} = a{j} * x^4 * (4j+1)/(4j+5)
            curr = curr * pow(x, 4) * (4.0 * j + 1.0) / (4.0 * j + 5.0); 
        }

        // 2. Считаем вторую сумму (se с точностью до eps=0.0001)
        se = 0; 
        int i = 0;
        double curr_eps = x; // начинаем с первого члена
        do 
        {
            se += curr_eps;
            // Рекуррентная формула для следующего члена
            curr_eps = curr_eps * pow(x, 4) * (4.0 * i + 1.0) / (4.0 * i + 5.0);
            i++;
        } while (abs(curr_eps) >= 0.0001); // Условие точности

        //вывод текущих сумм:
        cout << "Sn = " << sn << "    ";
        cout << "Se = " << se << "    ";
        
        // 3. Формула точного значения Y
        double y = 0.25 * log((1.0 + x) / (1.0 - x)) + 0.5 * atan(x);
        cout << "Y = " << y << endl;
    }

    //вывод результатов (значения для последнего X):
    cout << endl << "Результаты:" << endl;
    cout << "Сумма для заданного n = 3: " << sn << endl;
    cout << "Сумма для условия точности eps = " << se << endl;

    return 0; // конец программы
}